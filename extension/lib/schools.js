export function norm(s) {
  return String(s || '')
    .toLowerCase()
    .replace(/\s+/g, '')
    .replace(/^국립/, '')
    .replace(/(캠퍼스|본교)$/, '');
}

function autoAliases(name) {
  const a = [];
  if (name.endsWith('여자대학교')) a.push(name.replace(/여자대학교$/, '여대'));
  if (name.endsWith('대학교')) a.push(name.replace(/대학교$/, '대'));
  a.push('국립' + name);
  return a;
}

export const ALL_SCHOOLS = RAW.map(([name, region, ...aliases]) => ({
  name,
  region,
  aliases: [...new Set([...aliases, ...autoAliases(name)])],
}));

const INDEX = new Map();
for (const s of ALL_SCHOOLS) {
  for (const k of [s.name, ...s.aliases]) if (!INDEX.has(norm(k))) INDEX.set(norm(k), s.name);
}

/** 입력을 공식 이름으로. 없으면 null */
export function resolveSchool(input) {
  const k = norm(input);
  if (!k) return null;
  return INDEX.get(k) || null;
}

/** 검색창 자동완성: 정확히 일치 > 앞부분 일치 > 포함 순 */
export function searchSchools(q, limit = 8) {
  const k = norm(q);
  if (!k) return [];
  const scored = [];
  for (const s of ALL_SCHOOLS) {
    const keys = [s.name, ...s.aliases].map(norm);
    let best = 0;
    for (const key of keys) {
      if (key === k) best = Math.max(best, 3);
      else if (key.startsWith(k)) best = Math.max(best, 2);
      else if (key.includes(k)) best = Math.max(best, 1);
    }
    if (best) scored.push([best, s]);
  }
  return scored.sort((a, b) => b[0] - a[0] || a[1].name.localeCompare(b[1].name, 'ko')).slice(0, limit).map((x) => x[1]);
}
